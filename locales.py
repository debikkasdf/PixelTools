def tr(key: str, default: Optional[str] = None, **kwargs: Any) -> str:
    lang = get_current_language()
    dict_for_lang = TRANSLATIONS.get(lang) or TRANSLATIONS.get("en") or TRANSLATIONS["ru"]
    text = dict_for_lang.get(key)
    if text is None:
        det_map = DETECTOR_MESSAGES.get(lang, {})
        if key in det_map:
            text = det_map[key]
        elif isinstance(key, str) and key.strip() in det_map:
            text = det_map[key.strip()]
    if text is None:
        text = TRANSLATIONS.get("en", {}).get(key, TRANSLATIONS.get("ru", {}).get(key, default if default is not None else key))
    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text


def load_app_config() -> dict[str, Any]:
    try:
        if CONFIG_PATH.is_file():
            data = json.loads(CONFIG_PATH.read_text(encoding="utf-8"))
            if isinstance(data, dict):
                return data
    except Exception as exc:
        LOGGER.warning("Could not read %s: %s", CONFIG_PATH, exc)
    return {}


def save_app_config(updates: dict[str, Any]) -> None:
    try:
        CONFIG_PATH.parent.mkdir(parents=True, exist_ok=True)
        config = load_app_config()
        config.update(updates)
        CONFIG_PATH.write_text(json.dumps(config, indent=2, ensure_ascii=False), encoding="utf-8")
    except Exception as exc:
        LOGGER.warning("Could not save %s: %s", CONFIG_PATH, exc)
