def get_permission_label(permission: str) -> str:
    lang = get_current_language()
    dict_for_lang = PERMISSION_NAMES.get(lang) or PERMISSION_NAMES["en"]
    if permission in dict_for_lang:
        return dict_for_lang[permission]
    if permission in PERMISSION_NAMES["en"]:
        return PERMISSION_NAMES["en"][permission]
    short = permission.split(".")[-1]
    return " ".join(short.split("_")).title()


